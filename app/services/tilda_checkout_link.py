"""Authenticated-by-browser-secret Tilda checkout link, with no email or stock writes.

The secret is generated by the buyer's browser, transported alongside the real
Tilda webhook, and persisted only as its SHA-256 digest. Neither a draft ID nor
an email or telephone number is sufficient proof of checkout ownership.
"""
import hashlib
import os
import re

from sqlalchemy import select

from app.database.session import async_session
from app.models.draft_order import DraftOrder
from app.models.order_desk import OrderDesk
from app.services.order_desk import DeskError, DeskService

_NONCE = re.compile(r"[A-Za-z0-9_-]{43}\Z")


def checkout_nonce_hash(value: str) -> str:
    if not isinstance(value, str) or not _NONCE.fullmatch(value):
        raise ValueError("invalid_checkout_nonce")
    return hashlib.sha256(value.encode("ascii")).hexdigest()


async def issue_checkout_link(nonce: str) -> dict:
    if os.getenv("TILDA_CHECKOUT_LINK_ENABLED", "false").lower() != "true":
        raise DeskError("link_unavailable")
    try:
        digest = checkout_nonce_hash(nonce)
    except ValueError:
        raise DeskError("link_unavailable") from None

    async with async_session() as session:
        # Never look up by customer-entered contact information or predictable
        # Tilda order numbers. Reject a theoretically ambiguous JSON match.
        matches = (await session.scalars(
            select(DraftOrder.id).where(
                DraftOrder.contact_details["tilda_checkout_nonce_hash"].as_string() == digest
            ).limit(2)
        )).all()
        if len(matches) != 1:
            raise DeskError("link_unavailable")
        draft_id = matches[0]
        desk = await session.get(OrderDesk, draft_id)
        if not desk or desk.customer_telegram_id:
            raise DeskError("link_unavailable")

    # Existing row-locked issuing path: hashed token, short TTL, revocation of
    # unused predecessors, and fail-closed if Telegram was linked meanwhile.
    return await DeskService().issue_link(draft_id)
